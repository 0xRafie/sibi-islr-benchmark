"""LaTeX tables of the paper from the outputs of `analyze.py final` and `analyze.py perclass` (combined 114-class model,
within-category accuracy).

    python scripts/paper_tables.py --demo     # self-check on synthetic data
    python scripts/paper_tables.py            # -> paper/table_results.tex (Table III), paper/table_ablation.tex (Table IV)

Table III: the BiLSTM under SD, then the five models under SI, seed 0 for every model. Per-instance accuracy (P-I) in
every column, per-class accuracy (P-C) for words and Overall; bold = best under SI; * = differs significantly from the
BiLSTM in category P-I (family (a) of analyze.py, tested under SI only; SD is descriptive). Table IV: the fine-tuned
Uni-Sign and its three ablation variants under SI, same columns; * = Overall P-I differs from the full input.

Paths are relative to the working directory; environment variables move them:
    SIBI_QC    (default qc)     inputs $SIBI_QC/results/final_*.csv
    SIBI_PAPER (default paper)  outputs table_results.tex and table_ablation.tex
"""
import csv
import os
import sys

QC = os.environ.get("SIBI_QC", "qc")
PAPER = os.environ.get("SIBI_PAPER", "paper")
SUMMARY, TESTS, ABLASI = f"{QC}/results/final_summary.csv", f"{QC}/results/final_tests.csv", f"{QC}/results/final_ablasi_acc.csv"
PERCLASS, TESTS0 = f"{QC}/results/final_per_class.csv", f"{QC}/results/final_tests_seed0.csv"   # analyze.py perclass, seed 0
CATS = (("affix", "Affix"), ("number", "Number"), ("alphabet", "Alphabet"), ("kata", "Word"))
MODELS = {"bilstm": "BiLSTM", "signbart_am21": "SignBart", "dsta_am21": "DSTA-SLR", "unisign_ft": "Uni-Sign (pose)",
          "shubert_lora": "SHuBERT"}                  # row order, baseline first
INPUTS = {"bilstm": "MediaPipe", "signbart_am21": "MediaPipe", "dsta_am21": "RTMW", "unisign_ft": "RTMW",
          "shubert_lora": "DINOv2"}                     # input column in front of the model name
VARIANTS = {"unisign_ft_hands": "Hands only", "unisign_ft_thumbs": "Thumbs masked",
            "unisign_ft_face": "No face landmarks"}   # names and order as in figures.fig_ablation_unisign
SIG = "$^{*}$"                                     # significance mark
SRC = "% generated by scripts/paper_tables.py from the final_*.csv results of analyze.py; do not edit by hand\n"


def load(summary=SUMMARY, tests=TESTS0, perclass=PERCLASS):
    """-> ({(protocol, name): (accuracy, macro-F1)} over all seeds, {(family, category, model) decided to differ under
    SI, tested against BiLSTM seed 0}, {(protocol, model, category | overall): (P-I, P-C)} for seed 0 (Tables III, IV))."""
    s = {(r["protocol"], r["model"]): (float(r["acc"]), float(r["f1"]))
         for r in csv.DictReader(open(summary)) if r["setting"] == "combined"}
    dec = {(r["family"], r["category"], r["model"]) for r in csv.DictReader(open(tests))
           if r["protocol"] == "cl" and r["decision"] == "True"}
    pc = {(r["protocol"], r["model"], r["category"]): (float(r["pi"]), float(r["pc"])) for r in csv.DictReader(open(perclass))}
    return s, dec, pc


def table_results(s, dec, pc):
    """Table III: the BiLSTM under SD, then the five models under SI (Ho and Santoso's own numbers are not in the table).
    Per-instance accuracy (P-I) in every column, per-class accuracy (P-C) only where class sizes differ (words,
    Overall); no macro-F1. Bold = best under SI; * on within-category P-I (family a)."""
    cols = [(c, 0) for c, _ in CATS] + [("kata", 1), (None, 0), (None, 1)]   # (category | None = Overall, 0 = P-I | 1 = P-C)
    val = lambda p, m, c, k: pc[(p, m, c or "overall")][k]                  # seed 0 for every model
    best = {col: max(MODELS, key=lambda m: val("cl", m, *col)) for col in cols}

    def row(label, p, m, inp):
        cells = []
        for c, k in cols:
            x = f"{val(p, m, c, k):.2f}"
            if p == "cl" and best[(c, k)] == m:
                x = f"\\textbf{{{x}}}"
            cells.append(x + (SIG if p == "cl" and k == 0 and c and ("a", c, m) in dec else ""))
        return " & ".join([inp, label, {"cs": "SD", "cl": "SI"}[p]] + cells) + " \\\\"

    ms = list(MODELS)                                   # the input is written only on the first row of each group
    lines = [row("BiLSTM", "cs", "bilstm", INPUTS["bilstm"]), "\\hline"] + [
        row(MODELS[m], "cl", m, INPUTS[m] if i == 0 or INPUTS[ms[i - 1]] != INPUTS[m] else "") for i, m in enumerate(ms)]
    head = ("Input & Model & Evaluation & " + " & ".join(n for _, n in CATS[:3]) + " & \\multicolumn{2}{c}{Word} & "
            "\\multicolumn{2}{c}{Overall} \\\\\n & & & P-I & P-I & P-I & P-I & P-C & P-I & P-C \\\\")
    note = ("P-I: per-instance accuracy, within-category or, for Overall, 114-class; P-C: per-class accuracy (class mean), for "
            "words (109--989 clips per class) and Overall; \\%, averaged over folds. SD: "
            "signer-dependent, stratified 5-fold as used by Ho and Santoso; SI: signer-independent, leave-one-signer-out. Uni-Sign "
            "(pose) is its pose-only setting. Bold: best under SI. " + SIG + "Differs significantly from the BiLSTM in category P-I "
            "(two-sided Wilcoxon signed-rank test over the 22 SI folds, Holm-adjusted p $<$ 0.05).")   # at most three lines
    return (SRC + "\\begin{table*}[!t]\n\\caption{Recognition Results of the Five Models under SD and SI}\n\\label{tab:results}\n\\centering\\footnotesize\n\\setlength{\\tabcolsep}{4pt}\n"
            "\\begin{tabular}{lll" + "c" * len(cols) + "}\n\\hline\n" + head + "\n\\hline\n" + "\n".join(lines)
            + "\n\\hline\n\\end{tabular}\n\\par\\vspace{1mm}\\parbox{\\textwidth}{\\scriptsize " + note + "}\n\\end{table*}\n")


def load_ablation(path=ABLASI):
    """-> {(model, category): row of analyze.py ablasi}; category 'overall' = 114 classes over all clips."""
    return {(r["model"], r["category"]): r for r in csv.DictReader(open(path))}


def table_ablation(pc, ab):
    """Table IV: the fine-tuned Uni-Sign with full input and its three variants under SI, with the columns of Table III
    (P-I everywhere, P-C for words and Overall). * on Overall P-I: Wilcoxon test over the 22 folds, Holm per family
    (analyze.py ablasi with k=0)."""
    cols = [(c, 0) for c, _ in CATS] + [("kata", 1), ("overall", 0), ("overall", 1)]

    def row(label, m):
        cells = [f"{pc[('cl', m, c)][k]:.2f}" for c, k in cols]
        o = ab.get((m, "overall"))
        if o and o["decision"] == "True":
            cells[5] += SIG                                                  # Overall P-I = the tested metric
        return " & ".join([label] + cells) + " \\\\"

    head = (" & " + " & ".join(n for _, n in CATS[:3]) + " & \\multicolumn{2}{c}{Word} & \\multicolumn{2}{c}{Overall} \\\\\n"
            "Variant & P-I & P-I & P-I & P-I & P-C & P-I & P-C \\\\")
    note = ("Fine-tuned Uni-Sign, combined model, SI; P-I and P-C as in Table~\\ref{tab:results}, \\%. " + SIG
            + "Overall P-I significantly different from the full input (two-sided Wilcoxon signed-rank test over the 22 folds, "
            "Holm-adjusted p $<$ 0.05).")
    return (SRC + "\\begin{table}[!htbp]\n\\caption{Ablation of Input Keypoints of Uni-Sign (pose) under SI}\n\\label{tab:ablation}\n"
            "\\centering\\footnotesize\n\\setlength{\\tabcolsep}{1.8pt}\n\\begin{tabular}{l" + "c" * len(cols) + "}\n\\hline\n" + head
            + "\n\\hline\n" + "\n".join(row(n, m) for m, n in VARIANTS.items()) + "\n\\hline\n" + row("Full input", "unisign_ft")
            + "\n\\hline\n\\end{tabular}\n\\par\\vspace{1mm}\\parbox{\\linewidth}{\\scriptsize " + note + "}\n\\end{table}\n")


def demo():
    import tempfile
    cats = [c for c, _ in CATS] + ["overall"]
    ms = list(MODELS) + list(VARIANTS)
    pi = lambda m, j: 99 if (m, j) == ("unisign_ft", 0) else 60 + 3 * ms.index(m) + j    # SI per-instance accuracy
    rows = [("cs", "bilstm", c, 90 + j) for j, c in enumerate(cats)] + [("cl", m, c, pi(m, j)) for m in ms for j, c in enumerate(cats)]

    def write(path, head, body):
        with open(path, "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(head)
            w.writerows(body)
        return path

    with tempfile.TemporaryDirectory() as d:
        perclass = write(f"{d}/pc.csv", ["protocol", "model", "category", "runs", "pi", "pc"],
                         [(p, m, c, 22, v, v - 0.5) for p, m, c, v in rows])               # P-C = P-I - 0.5
        summary = write(f"{d}/summary.csv", ["setting", "protocol", "model", "acc", "f1"],
                        [("combined", p, m if c == "overall" else f"{m}|{c}", v, v - 1) for p, m, c, v in rows]
                        + [("affix", "cl", "unisign_ft", 0, 0)])                           # another setting: ignored
        tests = write(f"{d}/tests.csv", ["family", "protocol", "category", "model", "decision"],
                      [("a", "cl", "affix", "unisign_ft", True), ("a", "cl", "number", "unisign_ft", True),
                       ("a", "cl", "kata", "shubert_lora", True), ("a", "cl", "affix", "dsta_am21", False),
                       ("a", "cs", "affix", "signbart_am21", True)])                       # SD decision: ignored
        ablation = write(f"{d}/ablation.csv", ["model", "category", "decision"],
                         [("unisign_ft_hands", "overall", True), ("unisign_ft_thumbs", "overall", True),
                          ("unisign_ft_face", "overall", False), ("unisign_ft_hands", "affix", "")])
        s, dec, pc = load(summary, tests, perclass)
        assert all(abs(float(x["pi"]) - s[(x["protocol"], x["model"] + ("" if x["category"] == "overall" else "|" + x["category"]))][0])
                   < 1e-6 for x in csv.DictReader(open(perclass)) if x["model"] != "bilstm")   # one-seed models: P-I = summary
        ab = load_ablation(ablation)
    r = table_results(s, dec, pc)
    assert "MediaPipe & BiLSTM & SD & 90.00 & 91.00 & 92.00 & 93.00 & 92.50 & 94.00 & 93.50 \\\\" in r, r   # SD: no bold or *
    assert "MediaPipe & BiLSTM & SI & 60.00 & 61.00 & 62.00 & 63.00 & 62.50 & 64.00 & 63.50 \\\\" in r
    assert "\n & SignBart & SI & 63.00 & 64.00 &" in r and "RTMW & DSTA-SLR & SI & 66.00 &" in r and "F1" not in r
    assert "\n & Uni-Sign (pose) & SI & \\textbf{99.00}$^{*}$ & 70.00$^{*}$ & 71.00 & 72.00 & 71.50 & 73.00 & 72.50 \\\\" in r
    assert ("DINOv2 & SHuBERT & SI & 72.00 & \\textbf{73.00} & \\textbf{74.00} & \\textbf{75.00}$^{*}$ & \\textbf{74.50} & "
            "\\textbf{76.00} & \\textbf{75.50} \\\\") in r                              # * on P-I only, not on P-C
    assert "81.17" not in r and "reported" not in r and r.count("Ho and Santoso") == 1        # only in the note
    assert "seed" not in r and "cite" not in r
    assert r.count(SIG) == 3 + 1 and r.count("\\textbf") == 7                  # 3 decisions + the note; one best per column
    assert r.index("SignBart") < r.index("DSTA-SLR") < r.index("Uni-Sign") < r.index("SHuBERT")
    t = table_ablation(pc, ab)
    assert "Hands only & 75.00 & 76.00 & 77.00 & 78.00 & 77.50 & 79.00$^{*}$ & 78.50 \\\\" in t, t
    assert "Thumbs masked & 78.00 & 79.00 & 80.00 & 81.00 & 80.50 & 82.00$^{*}$ & 81.50 \\\\" in t
    assert "No face landmarks & 81.00 & 82.00 & 83.00 & 84.00 & 83.50 & 85.00 & 84.50 \\\\" in t
    assert "Full input & 99.00 & 70.00 & 71.00 & 72.00 & 71.50 & 73.00 & 72.50 \\\\" in t
    assert t.index("Hands only") < t.index("Thumbs masked") < t.index("No face landmarks") < t.index("Full input")   # full input last
    assert t.count(SIG) == 2 + 1 and "F1" not in t and "textbf" not in t and "BiLSTM" not in t
    print("demo ok: Table III (SD row descriptive, P-I in every column, P-C for words and Overall, bold per SI column, "
          "* for family (a) decisions) and Table IV (three variants, full input last, * on Overall P-I)")


if __name__ == "__main__":
    if "--demo" in sys.argv:
        demo()
    else:
        s, dec, pc = load()
        open(f"{PAPER}/table_results.tex", "w").write(table_results(s, dec, pc))
        open(f"{PAPER}/table_ablation.tex", "w").write(table_ablation(pc, load_ablation()))
        print(f"written: {PAPER}/table_results.tex, {PAPER}/table_ablation.tex")
